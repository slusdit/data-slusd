-- Role catalogue migration (branch roles-table-migration, 2026-10-28)
--
-- Turns the ROLE enum into a data-driven Role table so new roles (board
-- members, outside partners, anyone with no Aeries account) are rows created
-- on the admin Roles tab instead of schema changes.
--
-- WHAT IT DOES
--   Role            enum column -> VARCHAR(191) UNIQUE; adds label, description,
--                   isSystem, createdAt, updatedAt; drops the unused queryId
--                   (0 rows used it on 2026-10-28)
--   User            primaryRole enum -> VARCHAR(191) with a foreign key to
--                   Role.role (ON UPDATE CASCADE, ON DELETE RESTRICT)
--   _UserRole       dropped. Legacy implicit join table the app stopped reading
--                   when the explicit UserRole table arrived. Its 25 rows are
--                   listed at the bottom of this file for reference.
--   _QueryToRole    new implicit join table for per-report roles (the old
--                   design hung a queryId off Role; 0 reports used it)
--   BOARDMEMBER     inserted as the first data role
--
-- MySQL converts ENUM values to their string labels when the column type
-- changes, so no data rewrite is needed for `role` or `primaryRole`.
--
-- HOW TO RUN (see docs/roles-migration-2026-10.md for the full runbook)
--   1. Rehearse against a copy of the database first.
--   2. In the maintenance window, with the app stopped and a dump taken:
--        npx tsx scripts/snapshot-roles.ts > before.json
--        npx prisma db execute --file prisma/manual-migrations/2026-10-28-role-catalogue.sql
--        npx prisma migrate diff --from-config-datasource --to-schema prisma/schema.prisma --exit-code
--          (exit 0 = database now matches the schema)
--        npx tsx scripts/snapshot-roles.ts > after.json   (must equal before.json)
--   3. Deploy the build that goes with this schema.
--
-- ROLLBACK: restore the dump taken in step 2 and redeploy the previous build.
-- The statements below are not transactional in MySQL (DDL auto-commits).

